function crc32(data) {
  let crc = 0xffffffff;
  for (const b of data) {
    crc ^= b;
    for (let n = 0; n < 8; n++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function rarFixture() {
  const name = Buffer.from('rar-fixture.txt'),
    data = Buffer.from('RAR fixture generated by Muxplorer smoke\n');
  const header = (type, flags, length) => {
    const h = Buffer.alloc(length);
    h[2] = type;
    h.writeUInt16LE(flags, 3);
    h.writeUInt16LE(length, 5);
    return h;
  };
  const complete = (h) => {
    h.writeUInt16LE(crc32(h.subarray(2)) & 65535, 0);
    return h;
  };
  const file = header(0x74, 0x8000, 32 + name.length);
  file.writeUInt32LE(data.length, 7);
  file.writeUInt32LE(data.length, 11);
  file[15] = 3;
  file.writeUInt32LE(crc32(data), 16);
  file[24] = 20;
  file[25] = 0x30;
  file.writeUInt16LE(name.length, 26);
  file.writeUInt32LE(0x81a4, 28);
  name.copy(file, 32);
  return Buffer.concat([
    Buffer.from('526172211a0700', 'hex'),
    complete(header(0x73, 0, 13)),
    complete(file),
    data,
    complete(header(0x7b, 0, 7)),
  ]);
}
