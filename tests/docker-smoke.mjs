async function request(endpoint, body, expected = 200) {
  const response = await fetch(`${base}/api/${endpoint}`, {
    method: body === undefined ? 'GET' : 'POST',
    headers: { 'content-type': 'application/json', 'x-muxplorer': '1', cookie },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
  const data = await response.json();
  assert.equal(response.status, expected, `${endpoint}: ${JSON.stringify(data)}`);
  return data;
}
async function job(endpoint, body, status = 'completed') {
  const created = await request(endpoint, body, 201);
  for (let attempt = 0; attempt < 300; attempt++) {
    const jobs = await request('jobs');
    const current = jobs.find((item) => item.id === created.id);
    if (['completed', 'failed', 'cancelled', 'interrupted'].includes(current.status)) {
      assert.equal(current.status, status, JSON.stringify(current));
      return current;
    }
    await pause(100);
  }
  throw new Error(`Timeout waiting for ${created.id}`);
}
